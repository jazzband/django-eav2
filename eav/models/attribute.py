from __future__ import annotations

import warnings
from functools import cached_property
from typing import TYPE_CHECKING, Any

from django.contrib.contenttypes.models import ContentType
from django.core.exceptions import ValidationError
from django.db import models
from django.utils import timezone
from django.utils.translation import gettext_lazy as _

from eav import validators
from eav.fields import EavDatatypeField
from eav.logic.dates import as_datetime
from eav.logic.entity_pk import get_entity_pk_type
from eav.logic.managers import AttributeManager
from eav.logic.object_pk import get_pk_format
from eav.logic.slug import SLUGFIELD_MAX_LENGTH, generate_slug
from eav.models.enum_value import EnumValue
from eav.models.value import Value
from eav.settings import CHARFIELD_LENGTH, DESCRIPTION_LENGTH

if TYPE_CHECKING:
    from collections.abc import Callable, Collection

    from eav.models.enum_group import EnumGroup


class Attribute(models.Model):
    """Putting the **A** in *EAV*: the attributes, or concepts.

    Examples of possible *Attributes*: color, height, weight, number of
    children, number of patients, has fever?, etc...

    Each attribute has a name, and a description, along with a slug that must
    be unique.  If you don't provide a slug, a default slug (derived from
    name), will be created.

    The *required* field is a boolean that indicates whether this EAV attribute
    is required for entities to which it applies. It defaults to *False*.

    .. warning::
       Just like a normal model field that is required, you will not be able
       to save or create any entity object for which this attribute applies,
       without first setting this EAV attribute.

    There are 7 possible values for datatype:

        * int (TYPE_INT)
        * float (TYPE_FLOAT)
        * text (TYPE_TEXT)
        * date (TYPE_DATE)
        * bool (TYPE_BOOLEAN)
        * object (TYPE_OBJECT)
        * enum (TYPE_ENUM)
        * json (TYPE_JSON)
        * csv (TYPE_CSV)


    Examples::

        Attribute.objects.create(name='Height', datatype=Attribute.TYPE_INT)
        # = <Attribute: Height (Integer)>

        Attribute.objects.create(name='Color', datatype=Attribute.TYPE_TEXT)
        # = <Attribute: Color (Text)>

        yes = EnumValue.objects.create(value='yes')
        no = EnumValue.objects.create(value='no')
        unknown = EnumValue.objects.create(value='unknown')
        ynu = EnumGroup.objects.create(name='Yes / No / Unknown')
        ynu.values.add(yes, no, unknown)

        Attribute.objects.create(name='has fever?',
            datatype=Attribute.TYPE_ENUM,
            enum_group=ynu
        )
        # = <Attribute: has fever? (Multiple Choice)>

    .. warning:: Once an Attribute has been used by an entity, you can not
                 change it's datatype.
    """

    TYPE_TEXT = "text"
    TYPE_FLOAT = "float"
    TYPE_INT = "int"
    TYPE_DATE = "date"
    TYPE_BOOLEAN = "bool"
    TYPE_OBJECT = "object"
    TYPE_ENUM = "enum"
    TYPE_JSON = "json"
    TYPE_CSV = "csv"

    DATATYPE_CHOICES = (
        (TYPE_TEXT, _("Text")),
        (TYPE_DATE, _("Date")),
        (TYPE_FLOAT, _("Float")),
        (TYPE_INT, _("Integer")),
        (TYPE_BOOLEAN, _("True / False")),
        (TYPE_OBJECT, _("Django Object")),
        (TYPE_ENUM, _("Multiple Choice")),
        (TYPE_JSON, _("JSON Object")),
        (TYPE_CSV, _("Comma-Separated-Value")),
    )

    # Core attributes
    id = get_pk_format()

    datatype = EavDatatypeField(
        choices=DATATYPE_CHOICES,
        max_length=6,
        verbose_name=_("Data Type"),
    )

    name = models.CharField(
        max_length=CHARFIELD_LENGTH,
        help_text=_("User-friendly attribute name"),
        verbose_name=_("Name"),
    )

    """
    Main identifier for the attribute.
    Upon creation, slug is autogenerated from the name.
    (see :meth:`~eav.fields.EavSlugField.create_slug_from_name`).
    """
    slug = models.SlugField(
        max_length=SLUGFIELD_MAX_LENGTH,
        db_index=True,
        unique=True,
        help_text=_("Short unique attribute label"),
        verbose_name=_("Slug"),
    )

    """
    .. warning::
        This attribute should be used with caution. Setting this to *True*
        means that *all* entities that *can* have this attribute will
        be required to have a value for it.
    """
    required = models.BooleanField(
        default=False,
        verbose_name=_("Required"),
    )

    entity_ct = models.ManyToManyField(
        ContentType,
        blank=True,
        verbose_name=_("Entity content type"),
    )
    """
    This field allows you to specify a relationship with any number of content types.
    This would be useful, for example, if you wanted an attribute to apply only to
    a subset of entities. In that case, you could filter by content type in the
    :meth:`~eav.registry.EavConfig.get_attributes` method of that entity's config.
    """

    enum_group: models.ForeignKey[EnumGroup | None] = models.ForeignKey(
        "eav.EnumGroup",
        on_delete=models.PROTECT,
        blank=True,
        null=True,
        verbose_name=_("Choice Group"),
    )

    description = models.CharField(
        max_length=DESCRIPTION_LENGTH,
        blank=True,
        default="",
        help_text=_("Short description"),
        verbose_name=_("Description"),
    )

    # Useful meta-information

    display_order = models.PositiveIntegerField(
        default=1,
        verbose_name=_("Display order"),
    )

    modified = models.DateTimeField(
        auto_now=True,
        verbose_name=_("Modified"),
    )

    created = models.DateTimeField(
        default=timezone.now,
        editable=False,
        verbose_name=_("Created"),
    )

    objects = AttributeManager()

    class Meta:
        ordering = ("name",)
        verbose_name = _("Attribute")
        verbose_name_plural = _("Attributes")

    def __str__(self) -> str:
        display = self.get_datatype_display()  # pyright: ignore[reportAttributeAccessIssue]
        return f"{self.name} ({display})"

    def save(self, *args: Any, **kwargs: Any) -> None:
        """Save the Attribute, generating a slug if one wasn't provided."""
        if not self.slug:
            self.slug = generate_slug(self.name)

        self.full_clean()
        super().save(*args, **kwargs)

    def natural_key(self) -> tuple[str, str]:
        """
        Retrieve the natural key for the Attribute instance.

        The natural key for an Attribute is defined by its `name` and `slug`. This
        method returns a tuple containing these two attributes of the instance.

        Returns:
            tuple: A tuple containing the name and slug of the Attribute instance.
        """
        return (
            self.name,
            self.slug,
        )

    @property
    def help_text(self) -> str:
        """The attribute's description, used as help text in forms."""
        return self.description

    def get_validators(self) -> list[Callable[[Any], None]]:
        """Return the validators for the datatype, as a list of length one.

        The validator comes from :mod:`~eav.validators`.

        .. note::
           The reason it returns it as a list, is eventually we may want this
           method to look elsewhere for additional attribute specific
           validators to return as well as the default, built-in one.
        """
        datatype_validators = {
            "text": validators.validate_text,
            "float": validators.validate_float,
            "int": validators.validate_int,
            "date": validators.validate_date,
            "bool": validators.validate_bool,
            "object": validators.validate_object,
            "enum": validators.validate_enum,
            "json": validators.validate_json,
            "csv": validators.validate_csv,
        }

        return [datatype_validators[self.datatype]]

    def validate_value(self, candidate: Any) -> None:
        """Check *candidate* against the validators from :meth:`get_validators`."""
        for validator in self.get_validators():
            validator(candidate)

        if self.datatype == self.TYPE_ENUM:
            choice = candidate.value if isinstance(candidate, EnumValue) else candidate
            if choice not in self.enum_choices:
                raise ValidationError(
                    _("%(val)s is not a valid choice for %(attr)s")
                    % {"val": choice, "attr": self},
                )

    def validate_assignment(self, candidate: object) -> None:
        """
        Check a value assigned to this attribute of an entity.

        Raises ``ValidationError`` if the attribute is required and *candidate* is
        ``None``, or if *candidate* is not valid for the attribute.
        """
        if candidate is None:
            if self.required:
                raise ValidationError(_("%s EAV field cannot be blank") % self.slug)
            return

        try:
            self.validate_value(candidate)
        except ValidationError as err:
            raise ValidationError(
                _("%(attr)s EAV field %(err)s") % {"attr": self.slug, "err": err},
            ) from err

    @cached_property
    def enum_choices(self) -> dict[str, EnumValue]:
        """
        The choices of an enum attribute by value, loaded once per instance.

        Empty for attributes that are not of the enum datatype.
        """
        if self.enum_group is None:
            return {}

        return {choice.value: choice for choice in self.enum_group.values.all()}

    def clean(self) -> None:
        """Validate the attribute.

        Raises ``ValidationError`` if the datatype is *TYPE_ENUM* and no enum group is
        set, or if the datatype is not *TYPE_ENUM* and an enum group is set.
        """
        if self.datatype == self.TYPE_ENUM and not self.enum_group:
            raise ValidationError(
                _("You must set the choice group for multiple choice attributes"),
            )

        if self.datatype != self.TYPE_ENUM and self.enum_group:
            raise ValidationError(
                _("You can only assign a choice group to multiple choice attributes"),
            )

    def clean_fields(self, exclude: Collection[str] | None = None) -> None:
        """Perform field-specific validation on the model's fields.

        This method extends the default field cleaning process to include
        custom validation for the slug field.

        Args:
            exclude (list): Fields to exclude from cleaning.

        Raises:
            ValidationError: If the slug is not a valid Python identifier.
        """
        super().clean_fields(exclude=exclude)

        if not self.slug.isidentifier():
            warnings.warn(
                f"Slug '{self.slug}' is not a valid Python identifier. "
                + "Consider updating it.",
                stacklevel=3,
            )

    def get_choices(self) -> models.QuerySet[EnumValue] | None:
        """Return a query set of the :class:`EnumValue` objects of this attribute.

        Returns None if the datatype of this attribute is not *TYPE_ENUM*.
        """
        if self.datatype != Attribute.TYPE_ENUM or self.enum_group is None:
            return None

        return self.enum_group.values.all()

    def as_choice(self, raw_value: object) -> object:
        """Return the :class:`EnumValue` for text assigned to an enum attribute.

        Anything that is not text for an enum attribute is returned unchanged.
        """
        if (
            self.datatype != self.TYPE_ENUM
            or raw_value is None
            or isinstance(raw_value, EnumValue)
        ):
            return raw_value

        return self.enum_choices.get(str(raw_value)) or EnumValue.objects.get(
            value=raw_value,
        )

    def save_value(self, entity: models.Model, raw_value: object) -> Value | None:
        """Set the :class:`Value` of this attribute for *entity* to *raw_value*.

        *entity* is any Django object registered with eav.

        If a :class:`Value` object for this *entity* and attribute doesn't
        exist, one will be created.

        .. note::
           If *raw_value* is None and a :class:`Value` object exists for this
           Attribute and *entity*, it will delete that :class:`Value` object.
        """
        values = self.value_set.filter(**self._entity_filter(entity))  # pyright: ignore[reportAttributeAccessIssue]
        return self.store_value(entity, raw_value, values.first())

    def store_value(
        self,
        entity: models.Model,
        raw_value: object,
        existing: Value | None,
    ) -> Value | None:
        """Store *raw_value* for *entity*, given its *existing* :class:`Value`.

        The caller has already loaded *existing*. This is what :meth:`save_value` does
        once it has looked the object up, and what ``Entity.save`` calls with values it
        already holds.

        Returns the stored :class:`Value`, or ``None`` when nothing is stored.
        """
        if raw_value is None or raw_value == "":
            if existing is not None:
                existing.delete()
            return None

        stored = (
            as_datetime(raw_value) if self.datatype == self.TYPE_DATE else raw_value
        )

        if existing is None:
            existing = Value(attribute=self, **self._entity_filter(entity))
        elif stored == existing.value:
            return existing

        existing.value = stored
        existing.save_checked()
        return existing

    def _entity_filter(self, entity: models.Model) -> dict[str, object]:
        return {
            "entity_ct": ContentType.objects.get_for_model(entity),
            get_entity_pk_type(type(entity)): entity.pk,
        }
